-- 1. API_COMPANIES (파트너 업체 정보 & OAuth Client 자격증명)
CREATE TABLE API_COMPANIES (
    COMPANY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_NAME VARCHAR2(100) NOT NULL,
    BUSINESS_NUMBER VARCHAR2(50),
    CLIENT_ID VARCHAR2(100) NOT NULL UNIQUE,
    CLIENT_SECRET VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    DAILY_LIMIT NUMBER DEFAULT 10000 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE API_COMPANIES IS 'B2B 파트너 업체 정보 및 OAuth 2.0 Client 자격증명 테이블';
COMMENT ON COLUMN API_COMPANIES.COMPANY_ID IS '업체 고유 식별 PK ID';
COMMENT ON COLUMN API_COMPANIES.COMPANY_NAME IS '파트너 업체/회사명';
COMMENT ON COLUMN API_COMPANIES.BUSINESS_NUMBER IS '사업자등록번호';
COMMENT ON COLUMN API_COMPANIES.CLIENT_ID IS 'OAuth 2.0 Client ID (API 인증 키)';
COMMENT ON COLUMN API_COMPANIES.CLIENT_SECRET IS 'OAuth 2.0 Client Secret (API 시크릿 키)';
COMMENT ON COLUMN API_COMPANIES.STATUS IS '업체 계정 상태 (ACTIVE: 승인/활성, SUSPENDED: 정지)';
COMMENT ON COLUMN API_COMPANIES.DAILY_LIMIT IS '업체별 일일 API 호출 한도 건수';
COMMENT ON COLUMN API_COMPANIES.CREATED_AT IS '업체 등록 일시';


-- 2. API_COMPANY_TOKENS (업체 전용 OAuth 2.0 Access Tokens)
CREATE TABLE API_COMPANY_TOKENS (
    TOKEN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCESS_TOKEN VARCHAR2(500) NOT NULL UNIQUE,
    REFRESH_TOKEN VARCHAR2(500) UNIQUE,
    COMPANY_ID NUMBER NOT NULL,
    CLIENT_ID VARCHAR2(100) NOT NULL,
    SCOPE VARCHAR2(200) DEFAULT 'read,write',
    ACCESS_TOKEN_EXPIRES_AT TIMESTAMP NOT NULL,
    REFRESH_TOKEN_EXPIRES_AT TIMESTAMP,
    IS_REVOKED CHAR(1) DEFAULT 'N' CHECK (IS_REVOKED IN ('Y', 'N')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_COMP_TOKENS_COMP FOREIGN KEY (COMPANY_ID) REFERENCES API_COMPANIES(COMPANY_ID) ON DELETE CASCADE
);

COMMENT ON TABLE API_COMPANY_TOKENS IS 'B2B 파트너 업체 전용 발급 OAuth 2.0 Access Token 관리 테이블';
COMMENT ON COLUMN API_COMPANY_TOKENS.TOKEN_ID IS '토큰 레코드 PK ID';
COMMENT ON COLUMN API_COMPANY_TOKENS.ACCESS_TOKEN IS '발급된 24시간 Bearer Access Token 문자열';
COMMENT ON COLUMN API_COMPANY_TOKENS.REFRESH_TOKEN IS '토큰 갱신용 Refresh Token 문자열 (선택)';
COMMENT ON COLUMN API_COMPANY_TOKENS.COMPANY_ID IS '토큰을 소유한 파트너 업체 ID (FK)';
COMMENT ON COLUMN API_COMPANY_TOKENS.CLIENT_ID IS '발급에 사용된 Client ID';
COMMENT ON COLUMN API_COMPANY_TOKENS.SCOPE IS '토큰 접근 권한 범위 (read, write)';
COMMENT ON COLUMN API_COMPANY_TOKENS.ACCESS_TOKEN_EXPIRES_AT IS 'Access Token 만료 일시';
COMMENT ON COLUMN API_COMPANY_TOKENS.IS_REVOKED IS '토큰 폐기 여부 (Y: 폐기됨, N: 정상)';
COMMENT ON COLUMN API_COMPANY_TOKENS.CREATED_AT IS '토큰 발급 일시';


-- 3. API_POSTS (계층형 게시판 테이블)
CREATE TABLE API_POSTS (
    POST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_ID NUMBER,
    TITLE VARCHAR2(300) NOT NULL,
    CONTENT CLOB NOT NULL,
    AUTHOR_NAME VARCHAR2(100) NOT NULL,
    PARENT_ID NUMBER,
    GROUP_ID NUMBER,
    DEPTH NUMBER DEFAULT 0 NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    VIEW_COUNT NUMBER DEFAULT 0 NOT NULL,
    IS_DELETED CHAR(1) DEFAULT 'N' CHECK (IS_DELETED IN ('Y', 'N')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_POSTS_PARENT FOREIGN KEY (PARENT_ID) REFERENCES API_POSTS(POST_ID) ON DELETE CASCADE,
    CONSTRAINT FK_POSTS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES API_COMPANIES(COMPANY_ID) ON DELETE SET NULL
);

COMMENT ON TABLE API_POSTS IS '계층형 게시판 게시글 테이블';
COMMENT ON COLUMN API_POSTS.POST_ID IS '게시글 고유 PK ID';
COMMENT ON COLUMN API_POSTS.COMPANY_ID IS '작성자 소속 파트너 업체 ID (선택)';
COMMENT ON COLUMN API_POSTS.TITLE IS '게시글 제목';
COMMENT ON COLUMN API_POSTS.CONTENT IS '게시글 본문';
COMMENT ON COLUMN API_POSTS.AUTHOR_NAME IS '작성자 이름';
COMMENT ON COLUMN API_POSTS.PARENT_ID IS '상위 게시글 ID (원글인 경우 NULL)';
COMMENT ON COLUMN API_POSTS.GROUP_ID IS '최상위 게시글 그룹 ID';
COMMENT ON COLUMN API_POSTS.DEPTH IS '게시글 계층 깊이 (원글: 0, 답글: 1...)';
COMMENT ON COLUMN API_POSTS.SORT_ORDER IS '그룹 내 정렬 순서';
COMMENT ON COLUMN API_POSTS.VIEW_COUNT IS '조회수';
COMMENT ON COLUMN API_POSTS.IS_DELETED IS '삭제 여부 (Y: 삭제됨, N: 정상)';

CREATE INDEX IDX_POSTS_PARENT ON API_POSTS(PARENT_ID);
CREATE INDEX IDX_POSTS_GROUP ON API_POSTS(GROUP_ID, SORT_ORDER);


-- 4. API_COMMENTS (계층형 답글/댓글 테이블)
CREATE TABLE API_COMMENTS (
    COMMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_ID NUMBER NOT NULL,
    COMPANY_ID NUMBER,
    AUTHOR_NAME VARCHAR2(100) NOT NULL,
    CONTENT VARCHAR2(2000) NOT NULL,
    PARENT_ID NUMBER,
    GROUP_ID NUMBER,
    DEPTH NUMBER DEFAULT 0 NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    IS_DELETED CHAR(1) DEFAULT 'N' CHECK (IS_DELETED IN ('Y', 'N')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_COMMENTS_POST FOREIGN KEY (POST_ID) REFERENCES API_POSTS(POST_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENTS_PARENT FOREIGN KEY (PARENT_ID) REFERENCES API_COMMENTS(COMMENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENTS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES API_COMPANIES(COMPANY_ID) ON DELETE SET NULL
);

COMMENT ON TABLE API_COMMENTS IS '게시글 하위 계층형 답글/댓글 테이블';
COMMENT ON COLUMN API_COMMENTS.COMMENT_ID IS '댓글 고유 PK ID';
COMMENT ON COLUMN API_COMMENTS.POST_ID IS '대상 게시글 ID (FK)';
COMMENT ON COLUMN API_COMMENTS.COMPANY_ID IS '작성자 소속 파트너 업체 ID (선택)';
COMMENT ON COLUMN API_COMMENTS.AUTHOR_NAME IS '댓글 작성자 이름';
COMMENT ON COLUMN API_COMMENTS.CONTENT IS '댓글 내용';
COMMENT ON COLUMN API_COMMENTS.PARENT_ID IS '상위 댓글 ID (최상위 댓글인 경우 NULL)';
COMMENT ON COLUMN API_COMMENTS.GROUP_ID IS '최상위 댓글 그룹 ID';
COMMENT ON COLUMN API_COMMENTS.DEPTH IS '댓글 계층 깊이 (댓글: 0, 대댓글: 1...)';
COMMENT ON COLUMN API_COMMENTS.SORT_ORDER IS '그룹 내 정렬 순서';
COMMENT ON COLUMN API_COMMENTS.IS_DELETED IS '삭제 여부 (Y: 삭제됨, N: 정상)';

CREATE INDEX IDX_COMMENTS_POST ON API_COMMENTS(POST_ID);
CREATE INDEX IDX_COMMENTS_PARENT ON API_COMMENTS(PARENT_ID);
CREATE INDEX IDX_COMMENTS_GROUP ON API_COMMENTS(GROUP_ID, SORT_ORDER);


-- 4. API_CALL_LOGS (업체별 API 실시간 호출 로그 트래킹)
CREATE TABLE API_CALL_LOGS (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_ID NUMBER NOT NULL,
    ENDPOINT VARCHAR2(200) NOT NULL,
    HTTP_METHOD VARCHAR2(10) NOT NULL,
    STATUS_CODE NUMBER NOT NULL,
    IP_ADDRESS VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_LOGS_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES API_COMPANIES(COMPANY_ID) ON DELETE CASCADE
);

COMMENT ON TABLE API_CALL_LOGS IS 'B2B 파트너 업체별 API 실시간 호출 및 트래킹 로그 테이블';
COMMENT ON COLUMN API_CALL_LOGS.LOG_ID IS '호출 로그 PK ID';
COMMENT ON COLUMN API_CALL_LOGS.COMPANY_ID IS 'API를 호출한 파트너 업체 ID (FK)';
COMMENT ON COLUMN API_CALL_LOGS.ENDPOINT IS '호출된 API 엔드포인트 경로 (예: /api/v1/movies)';
COMMENT ON COLUMN API_CALL_LOGS.HTTP_METHOD IS 'HTTP 메서드 (GET, POST 등)';
COMMENT ON COLUMN API_CALL_LOGS.STATUS_CODE IS 'HTTP 응답 상태 코드 (200, 401 등)';
COMMENT ON COLUMN API_CALL_LOGS.IP_ADDRESS IS '호출 클라이언트 IP 주소';
COMMENT ON COLUMN API_CALL_LOGS.CREATED_AT IS 'API 호출 일시';


-- 5. API_TODO (업체별 할일 데이터 자원)
CREATE TABLE API_TODO (
    TODO_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPANY_ID NUMBER NOT NULL,
    TITLE VARCHAR2(500) NOT NULL,
    IS_COMPLETED CHAR(1) DEFAULT 'N' CHECK (IS_COMPLETED IN ('Y', 'N')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_TODO_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES API_COMPANIES(COMPANY_ID) ON DELETE CASCADE
);

COMMENT ON TABLE API_TODO IS 'B2B 파트너 업체별 할일(TODO) 데이터 자원 테이블';
COMMENT ON COLUMN API_TODO.TODO_ID IS 'TODO 고유 PK ID';
COMMENT ON COLUMN API_TODO.COMPANY_ID IS 'TODO를 소유한 파트너 업체 ID (FK)';
COMMENT ON COLUMN API_TODO.TITLE IS '할일 내용';
COMMENT ON COLUMN API_TODO.IS_COMPLETED IS '완료/체크 여부 (Y: 완료/체크됨, N: 미완료/미체크)';
COMMENT ON COLUMN API_TODO.CREATED_AT IS '할일 등록 일시';
COMMENT ON COLUMN API_TODO.COMPLETED_AT IS '할일 완료 일시';



